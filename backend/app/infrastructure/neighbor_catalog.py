class StaticNeighborRepository:
    def __init__(self, neighbors: tuple[Neighbor, ...] = NEIGHBORS) -> None:
        self._neighbors = {neighbor.id: neighbor for neighbor in neighbors}

    def get(self, neighbor_id: str) -> Neighbor | None:
        return self._neighbors.get(neighbor_id)

    def ids(self) -> tuple[str, ...]:
        return tuple(self._neighbors)
